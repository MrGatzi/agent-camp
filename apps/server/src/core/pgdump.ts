/**
 * Turns the /api/export tables into a Postgres dump (DDL + COPY blocks) that `psql -f` loads.
 * Used by apps/server/scripts/export-postgres.ts.
 */
import type { ExportColumn, ExportTable } from "./store.ts";

export type ExportValue = string | number | null | { $base64: string };

const ident = (name: string) => `"${name.replaceAll('"', '""')}"`;

function pgType(c: ExportColumn): string {
  const t = c.type.toUpperCase();
  if (t.includes("INT")) return "BIGINT";
  if (t.includes("BLOB")) return "BYTEA";
  if (t.includes("REAL") || t.includes("FLOA") || t.includes("DOUB")) return "DOUBLE PRECISION";
  return "TEXT";
}

const isIdentity = (t: ExportTable, c: ExportColumn) =>
  c.pk === 1 &&
  t.columns.filter((x) => x.pk > 0).length === 1 &&
  pgType(c) === "BIGINT" &&
  /\bAUTOINCREMENT\b/i.test(t.sql);

const isUnique = (t: ExportTable, c: ExportColumn) =>
  new RegExp(`(?:^|[(,\\s])"?${c.name}"?\\s[^,]*?\\bUNIQUE\\b`, "i").test(t.sql);

export function pgCreateTable(t: ExportTable): string {
  const pks = t.columns.filter((c) => c.pk > 0).sort((a, b) => a.pk - b.pk);
  const cols = t.columns.map((c) => {
    if (isIdentity(t, c)) return `  ${ident(c.name)} BIGINT GENERATED BY DEFAULT AS IDENTITY`;
    const notNull = c.notNull || c.pk > 0 ? " NOT NULL" : "";
    return `  ${ident(c.name)} ${pgType(c)}${notNull}${isUnique(t, c) ? " UNIQUE" : ""}`;
  });
  if (pks.length) cols.push(`  PRIMARY KEY (${pks.map((c) => ident(c.name)).join(", ")})`);
  const original = t.sql
    .split("\n")
    .map((l) => `-- ${l}`)
    .join("\n");
  return `-- ${t.name}: ${t.rows} rows; SQLite schema:\n${original}\nCREATE TABLE ${ident(t.name)} (\n${cols.join(",\n")}\n);\n`;
}

export const pgCopyStart = (t: ExportTable) =>
  `COPY ${ident(t.name)} (${t.columns.map((c) => ident(c.name)).join(", ")}) FROM stdin;\n`;
export const PG_COPY_END = "\\.\n\n";

const escapeCopy = (s: string) =>
  s.replace(/\\/g, "\\\\").replace(/\n/g, "\\n").replace(/\r/g, "\\r").replace(/\t/g, "\\t");

function hex(bytes: Uint8Array): string {
  let s = "";
  for (const b of bytes) s += b.toString(16).padStart(2, "0");
  return s;
}

function copyValue(c: ExportColumn, v: ExportValue): string {
  if (v === null) return "\\N";
  if (typeof v === "object")
    return `\\\\x${hex(Uint8Array.from(atob(v.$base64), (ch) => ch.charCodeAt(0)))}`;
  if (pgType(c) === "BYTEA") return `\\\\x${hex(new TextEncoder().encode(String(v)))}`;
  return escapeCopy(String(v));
}

export const pgCopyRow = (t: ExportTable, values: readonly ExportValue[]) =>
  `${t.columns.map((c, i) => copyValue(c, values[i] ?? null)).join("\t")}\n`;

/** Indexes (SQLite index DDL is valid Postgres) and identity counters after the data. */
export function pgFinishTable(t: ExportTable): string {
  const out = t.indexes.map((sql) => `${sql};\n`);
  for (const c of t.columns.filter((c) => isIdentity(t, c)))
    out.push(
      `SELECT setval(pg_get_serial_sequence('${ident(t.name)}', '${c.name}'), COALESCE((SELECT MAX(${ident(c.name)}) FROM ${ident(t.name)}), 0) + 1, false);\n`,
    );
  return out.join("");
}
